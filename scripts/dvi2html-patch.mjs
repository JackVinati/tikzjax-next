/**
 * The two changes the build makes to @drgrice1/dvi2html, applied wherever dvi2html is bundled: the
 * shipped worker (scripts/engine-assets.mjs) and every script that renders through the engine. Both
 * are about characters that TeX sets and the shipped faces can draw, and that cost the whole diagram.
 *
 * 1. dvi2html's TFM reader skips the last character of every font. The reader takes the font's
 * character range from its header, where `ec` — the largest character code — is inclusive, and
 * counts it that way itself (`number_of_chars = ec - bc + 1`). Then it reads the metrics with
 *
 *     for (let c = this.smallest_character_code; c < this.largest_character_code; ++c)
 *
 * which stops one short. All 112 fonts in its built-in table end on a character with a real
 * width, and in every one of them that character has no metrics, so a DVI that sets it fails with
 * "Could not find font metric for 127" and the whole diagram is lost. In cmr10 that character is
 * the dieresis accent, so ä, ö, ü — typed, or written as \"u — all failed; in cmsy10 it is
 * \spadesuit, in msbm10 \backepsilon. The glyphs were never missing: the shipped WOFF2 faces carry
 * them, and dvi2html's own glyph map points at them. Upstream: src/tfm/index.ts.
 *
 * 2. dvi2html's glyph map has holes. It draws character c of a font as one codepoint of that font's
 * BaKoMa face, looked up in a table generated by matching each BaKoMa glyph's name against the name
 * dvips-all.enc gives the character, and where the two names differ the character has no entry.
 * putText then reads `.toString(16)` off undefined — "Cannot read properties of undefined (reading
 * 'toString')" — and the diagram is lost. Of the characters its 112 fonts have metrics for, 302 have
 * no entry: 32 in the roman, bold, slanted, italic and sans text fonts, the stroke LaTeX's \L and \l
 * set over an L and an l, so Ł and ł failed however they were written; 36 in the text italics, which
 * is £ there where the upright fonts have $; the symbols in lasy; and some of cmtex and cmvtt.
 *
 * BaKoMa puts character c of every face at the same codepoint: U+F0A1 + c below 10, U+F0A3 + c up to
 * 32, U+F000 + c up to 126, U+F0C4 for 127. The table agrees with that for 13,120 of the 13,128
 * characters it has, measured against the shipped faces — the eight others are in cmtex and cmvtt,
 * and stay as the table has them — and every one of the 302 is in its face at that codepoint. So
 * the patched lookup falls back to it, and only where the table has nothing: a character that drew
 * before draws exactly as it did. Upstream: src/html.ts putText, the table from tools/glyphs.js.
 *
 * Upstream (drgrice1/dvi2html, read at d6ad7690) has both, and the package has not been released
 * since January 2025. Each fix is one expression, so they are patched here rather than forked, in
 * the manner of internal/DECISIONS.md D11: each edit must match exactly once before and be present
 * after, and a build that bundles dvi2html without passing through it fails, so neither can
 * silently become a no-op. Every fixture renders byte-identically with and without them, since no
 * fixture used one of those characters until it could.
 */
import { readFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import esbuild from 'esbuild';

/** The file the patch applies to: the package's one bundled entry point. */
const DVI2HTML_ENTRY = /[\\/]@drgrice1[\\/]dvi2html[\\/]dist[\\/]index\.js$/;

/**
 * The loop in TFM's read_characters, as the minified bundle spells it. The loop variable's name is
 * whatever the minifier chose, so it is matched rather than written down.
 */
const READ_CHARACTERS = /(for\(let (\w+)=this\.smallest_character_code;\2)<(this\.largest_character_code;)/g;
const READ_CHARACTERS_FIXED =
	/for\(let (\w+)=this\.smallest_character_code;\1<=this\.largest_character_code;/;

/**
 * The glyph lookup in putText, `table[this.font.name][c.toString()].toString(16)` as the minified
 * bundle spells it, the table's and the character's names being the minifier's.
 */
const GLYPH_LOOKUP = /(\w+)\[this\.font\.name\]\[(\w+)\.toString\(\)\]\.toString\(16\)/g;
const GLYPH_LOOKUP_FIXED =
	/\(\w+\[this\.font\.name\]\[(\w+)\.toString\(\)\]\?\?\(\1<10\?0xf0a1\+\1:\1<33\?0xf0a3\+\1:\1<127\?0xf000\+\1:0xf0c4\)\)\.toString\(16\)/;

/** One edit to the bundle, made only when its pattern matches exactly once, and checked after. */
function patchOnce(code, pattern, replacement, fixed, what, defect) {
	const found = code.match(pattern) ?? [];
	if (found.length !== 1) {
		throw new Error(
			`dvi2html patch: expected exactly one ${what}, found ${found.length}. ` +
				`@drgrice1/dvi2html has changed; check whether it still ${defect} ` +
				'(scripts/dvi2html-patch.mjs) and update or retire the patch.',
		);
	}
	const patched = code.replace(pattern, replacement);
	if (!fixed.test(patched))
		throw new Error(`dvi2html patch: applied to the ${what}, but not present after`);
	return patched;
}

/**
 * dvi2html's bundle with its TFM reader reading the last character too, and its glyph lookup
 * falling back to BaKoMa's own codepoint for a character its table lacks. Throws if it cannot be sure.
 */
export function patchDvi2html(code) {
	const tfm = patchOnce(
		code,
		READ_CHARACTERS,
		'$1<=$3',
		READ_CHARACTERS_FIXED,
		'TFM read_characters loop',
		'drops the last character of every font',
	);
	return patchOnce(
		tfm,
		GLYPH_LOOKUP,
		(_, table, c) =>
			`(${table}[this.font.name][${c}.toString()]??` +
			`(${c}<10?0xf0a1+${c}:${c}<33?0xf0a3+${c}:${c}<127?0xf000+${c}:0xf0c4)).toString(16)`,
		GLYPH_LOOKUP_FIXED,
		'glyph lookup',
		'has no glyph map entry for character 32 of cmr10, the stroke of Ł',
	);
}

/** esbuild plugin applying patchDvi2html. A build that bundles nothing to patch is an error. */
export function dvi2htmlPatch() {
	return {
		name: 'dvi2html-patch',
		setup(build) {
			let applied = 0;
			build.onStart(() => {
				applied = 0;
			});
			build.onLoad({ filter: DVI2HTML_ENTRY }, (args) => {
				applied++;
				return { contents: patchDvi2html(readFileSync(args.path, 'utf8')), loader: 'js' };
			});
			build.onEnd((result) => {
				// Zero means dvi2html reached the bundle by some other path — a new entry file, a
				// different package layout — and went in unpatched.
				if (result.errors.length === 0 && applied !== 1)
					throw new Error(`dvi2html patch: applied ${applied} times in one build, expected once`);
			});
		},
	};
}

/**
 * engine-src/library.ts and the patched dvi2html, bundled together for Node and imported: the
 * fork's exports plus `dvi2html`, and the worker's own `buildInput` (engine-src/document.ts) and
 * `restoreUnicode` (engine-src/unicode.ts). For the scripts that run the engine outside a worker,
 * so they assemble TeX's input and draw the result exactly as the plugin does. `name` keeps
 * concurrent scripts out of each other's way under node_modules/.cache.
 */
export async function importEngineForNode(root, name) {
	const dir = join(root, 'node_modules', '.cache', name);
	mkdirSync(dir, { recursive: true });
	const outfile = join(dir, 'engine.mjs');
	await esbuild.build({
		stdin: {
			contents: [
				"export * from './engine-src/library.ts';",
				"export { buildInput } from './engine-src/document.ts';",
				"export { restoreUnicode } from './engine-src/unicode.ts';",
				"export { dvi2html } from '@drgrice1/dvi2html';",
			].join('\n'),
			resolveDir: root,
			sourcefile: 'engine-for-node.ts',
			loader: 'ts',
		},
		outfile,
		bundle: true,
		format: 'esm',
		platform: 'node',
		logLevel: 'warning',
		plugins: [dvi2htmlPatch()],
	});
	return import(pathToFileURL(outfile).href);
}
